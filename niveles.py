# el jugador tenga caminos alternativos y pueda esquivar al cazador -
# un laberinto "perfecto" puro es un árbol, sin loops, y eso hace
# imposible esquivar en un pasillo). Ver /generar_niveles.py en la
# raíz del repo (no forma parte del juego en sí).
# Validado automáticamente:
#   - Siempre existe un camino físico de P a S.
#   - Todas las llaves de un nivel están ubicadas ANTES de cualquier
#     compuerta (nunca hace falta una llave para llegar a otra llave).
#   - Las bifurcaciones agregadas nunca conectan dos regiones separadas
#     por una compuerta (así la mecánica de "necesitás la llave" sigue
#     intacta, solo cambia que cada tramo deja de ser un pasillo único).
